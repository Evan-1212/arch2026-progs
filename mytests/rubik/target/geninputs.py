#!/usr/bin/env python3
"""Write the inputs of mytests/rubik/target/verify.c.

Usage: geninputs.py <ref-inputs-output> <output-dir> [extra-states-file]

Reads the "@@input kind state distance" lines of `ref inputs K` and, when
given, a file of further states (one per line; the distance is left to the
host reference). Writes into the output directory:
  verify_inputs.h   the C arrays states[] and invalid[]
  states.tsv        index, kind, state, distance (-1 when not listed)
  invalid.tsv       index, class, the input as a Python bytes literal
Exit status 0, or 1 when an input line is malformed.
"""

import re
import sys

STATE = re.compile(r"^[1-7]{7}[1-3]{7}$")

# The -1 rule of rubik.h, one class per reason. No entry is a valid state.
INVALID = [
    ("length", b""),
    ("length", b"1"),
    ("length", b"1234567"),
    ("length", b"1234567111111"),
    ("length", b"123456711111111"),
    ("length", b"1234567111111111"),
    ("length", b"12345671111111 "),
    ("length", b"1234567312312"),
    ("range", b"02345671111111"),
    ("range", b"82345671111111"),
    ("range", b"12345601111111"),
    ("range", b"12345670111111"),
    ("range", b"12345671111114"),
    ("range", b"12345671111110"),
    ("range", b"1234567111111a"),
    ("range", b"a2345671111111"),
    ("range", b"12345 71111111"),
    ("range", b"\xff2345671111111"),
    ("range", b"1234567\xb1111111"),
    ("repeat", b"11345671111111"),
    ("repeat", b"12345661111111"),
    ("repeat", b"77777771111111"),
    ("repeat", b"12345171111111"),
    ("sum", b"12345671111112"),
    ("sum", b"12345671111113"),
    ("sum", b"12345672111111"),
    ("sum", b"12345673333333"),
    ("sum", b"12345671111122"),
    ("sum", b"76543213213212"),
]


def c_literal(data):
    """A C string literal with every byte written as an octal escape."""
    return '"' + "".join(f"\\{b:03o}" for b in data) + '"'


def main():
    if len(sys.argv) not in (3, 4):
        print(__doc__, file=sys.stderr)
        return 2
    rows = []
    with open(sys.argv[1], encoding="ascii") as f:
        far, rest = [], []
        for line in f:
            if not line.startswith("@@input "):
                continue
            parts = line.split()
            if len(parts) != 4 or not STATE.match(parts[2]):
                print(f"bad input line: {line!r}", file=sys.stderr)
                return 1
            (far if parts[1] == "far" else rest).append((parts[1], parts[2], int(parts[3])))
    rows += far
    if len(sys.argv) == 4:
        with open(sys.argv[3], encoding="ascii") as f:
            for line in f:
                s = line.strip()
                if not s:
                    continue
                if not STATE.match(s):
                    print(f"bad extra state: {line!r}", file=sys.stderr)
                    return 1
                rows.append(("extra", s, -1))
    rows += rest
    out = sys.argv[2]
    with open(f"{out}/verify_inputs.h", "x", encoding="ascii") as f:
        f.write("/* Generated by mytests/rubik/target/geninputs.py. */\n")
        f.write("static const char *const states[] = {\n")
        for _, s, _ in rows:
            f.write(f'    "{s}",\n')
        f.write("};\nstatic const char *const invalid[] = {\n")
        for _, data in INVALID:
            f.write(f"    {c_literal(data)},\n")
        f.write("};\n")
    with open(f"{out}/states.tsv", "x", encoding="ascii") as f:
        for i, (kind, s, d) in enumerate(rows):
            f.write(f"{i}\t{kind}\t{s}\t{d}\n")
    with open(f"{out}/invalid.tsv", "x", encoding="ascii") as f:
        for i, (cls, data) in enumerate(INVALID):
            f.write(f"{i}\t{cls}\t{data!r}\n")
    kinds = {}
    for kind, _, _ in rows:
        kinds[kind] = kinds.get(kind, 0) + 1
    print(f"inputs: states={len(rows)} {kinds} invalid={len(INVALID)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
